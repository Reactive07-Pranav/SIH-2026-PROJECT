const dict: Record<Lang, Record<Key, string>> = { en, hi }

type T = (key: Key, vars?: Record<string, string | number>) => string

interface I18n { lang: Lang; setLang: (l: Lang) => void; t: T; fmtDate: (iso: string) => string }

const Ctx = createContext<I18n>(null!)
export const useI18n = () => useContext(Ctx)

function readLang(): Lang {
  try { return localStorage.getItem('lang') === 'hi' ? 'hi' : 'en' } catch { return 'en' }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readLang)

  useEffect(() => { document.documentElement.lang = lang }, [lang])

  function setLang(l: Lang) {
    setLangState(l)
    try { localStorage.setItem('lang', l) } catch { /* private mode: per-session only */ }
  }

  const t: T = (key, vars) => {
    let s = dict[lang][key] ?? en[key]
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
    return s
  }

  const fmtDate = (iso: string) =>
    new Date(iso).toLocaleString(lang === 'hi' ? 'hi-IN' : 'en-IN', { dateStyle: 'medium', timeStyle: 'short' })

  return <Ctx.Provider value={{ lang, setLang, t, fmtDate }}>{children}</Ctx.Provider>
}
